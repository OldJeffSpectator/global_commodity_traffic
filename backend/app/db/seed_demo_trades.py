def seed_demo_trades():
    db = SessionLocal()
    try:
        valid_isos = {c.iso3 for c in db.query(Country).all()}

        added = 0
        for reporter, partner, commodity, year, exp, imp, weight in DEMO_TRADES:
            if reporter not in valid_isos or partner not in valid_isos:
                continue

            existing = (
                db.query(BilateralTrade)
                .filter_by(
                    reporter_iso3=reporter,
                    partner_iso3=partner,
                    commodity_code=commodity,
                    year=year,
                )
                .first()
            )
            if not existing:
                db.add(BilateralTrade(
                    reporter_iso3=reporter,
                    partner_iso3=partner,
                    commodity_code=commodity,
                    year=year,
                    export_value_usd=exp,
                    import_value_usd=imp,
                    weight_kg=weight,
                ))
                added += 1

        db.commit()
        print(f"Demo trades seeded: {added} records added.")
    finally:
        db.close()


if __name__ == "__main__":
    seed_demo_trades()
